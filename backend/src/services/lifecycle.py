"""Footfall sample voiding and the contamination cascade it triggers.

A sample may be voided when its counts were recorded incorrectly.  The
observation is preserved for traceability, but it is excluded from live
analysis.  Any analysis that consumed the sample is invalidated, and any
brief derived from such an analysis is stopped or retracted.

The cascade is intentionally idempotent: retrying a failed void never
creates duplicate invalidation/retraction records.
"""

from fastapi import HTTPException
from sqlalchemy import select
from sqlalchemy.orm import Session

from src.models import (
    AnalysisInvalidation,
    AnalysisRun,
    AttributionCorrection,
    Brief,
    BriefInvalidation,
    FootfallSample,
    SampleVoid,
    User,
)
from src.services.audit import record

VOID_ISSUE_REASON = '计数录错，已报废'


def voided_sample_ids(db: Session, sample_ids) -> set[int]:
    ids = [int(i) for i in sample_ids]
    if not ids:
        return set()
    return set(db.scalars(select(SampleVoid.sample_id).where(SampleVoid.sample_id.in_(ids))))


def contaminated_analysis(db: Session, run: AnalysisRun) -> SampleVoid | None:
    """Return the first void record contaminating an analysis, if any.

    Checking the void table (not just the run status) closes the race where an
    analysis finishes after its sample has already been voided.
    """
    ids = list(run.sample_ids or ())
    if not ids:
        return None
    # This is a secondary guard.  The authoritative signal is the analysis
    # status, which the void sets while holding the analysis row lock; callers
    # re-read it with FOR UPDATE so a concurrent void serializes correctly.
    return db.scalar(select(SampleVoid).where(SampleVoid.sample_id.in_(ids)).limit(1))


def analysis_invalidation(db: Session, analysis_id: int) -> AnalysisInvalidation | None:
    return db.scalar(
        select(AnalysisInvalidation).where(AnalysisInvalidation.analysis_id == analysis_id)
    )


def brief_invalidation(db: Session, brief_id: int) -> BriefInvalidation | None:
    return db.scalar(select(BriefInvalidation).where(BriefInvalidation.brief_id == brief_id))


def affected_sample_ids(db: Session, sample: FootfallSample) -> set[int]:
    """The voided observation plus every sample that reuses its counts.

    A correction re-uses the original footfall/transaction/revenue values, so
    the replacement generated by an approved correction is contaminated too.
    Walking the link in both directions covers voiding either the original or
    the replacement sample.
    """
    affected = {sample.id}
    for correction in db.scalars(
        select(AttributionCorrection).where(
            (AttributionCorrection.sample_id == sample.id)
            | (AttributionCorrection.replacement_sample_id == sample.id)
        )
    ):
        affected.add(correction.sample_id)
        if correction.replacement_sample_id is not None:
            affected.add(correction.replacement_sample_id)
    return affected


def _invalidate_analyses(db: Session, affected: set[int], sample_id: int, reason: str):
    # Lock analyses first; issue/review/brief creation lock the same rows in
    # the same order so a concurrent issue cannot outlive the void.
    runs = list(db.scalars(select(AnalysisRun).with_for_update()))
    changed: list[AnalysisRun] = []
    touched: list[AnalysisRun] = []
    for run in runs:
        if not (set(run.sample_ids or ()) & affected):
            continue
        touched.append(run)
        if analysis_invalidation(db, run.id) is None:
            db.add(AnalysisInvalidation(
                analysis_id=run.id, sample_id=sample_id, reason=reason,
            ))
        if run.status != 'invalidated':
            run.status = 'invalidated'
            run.review_status = 'blocked'
            changed.append(run)
    return touched, changed


def _invalidate_briefs(db: Session, runs: list[AnalysisRun], reason: str,
                       actor: User):
    """Stop drafts and retract issued briefs for invalidated analyses.

    Returns ``(briefs, newly_changed)``; only newly changed briefs should be
    audited so a retried void does not duplicate the record.
    """
    if not runs:
        return [], []
    analysis_ids = [run.id for run in runs]
    briefs = list(db.scalars(
        select(Brief).where(Brief.analysis_id.in_(analysis_ids)).with_for_update()
    ))
    newly_changed: list[Brief] = []
    for brief in briefs:
        if brief.status not in ('draft', 'issued'):
            continue
        existing = brief_invalidation(db, brief.id)
        if brief.status == 'issued':
            # Keep title/summary/recommended_stalls and issued_at untouched so
            # the retracted brief still shows the original text and send time.
            if existing is None:
                db.add(BriefInvalidation(
                    brief_id=brief.id, kind='retracted', reason=reason, actor_id=actor.id,
                ))
            brief.status = 'retracted'
            newly_changed.append(brief)
        else:
            if existing is None:
                db.add(BriefInvalidation(
                    brief_id=brief.id, kind='blocked', reason=reason, actor_id=actor.id,
                ))
            brief.status = 'blocked'
            newly_changed.append(brief)
    return briefs, newly_changed


def void_sample(db: Session, sample_id: int, reason: str, actor: User) -> dict:
    sample = db.get(FootfallSample, sample_id, with_for_update=True)
    if sample is None:
        raise HTTPException(404, '客流样本不存在')

    affected = affected_sample_ids(db, sample)
    # Lock every affected observation in a stable order before writing.
    for sid in sorted(affected):
        if sid != sample.id:
            db.get(FootfallSample, sid, with_for_update=True)

    void = db.scalar(select(SampleVoid).where(SampleVoid.sample_id == sample.id))
    created = void is None
    if created:
        void = SampleVoid(
            sample_id=sample.id, reason=reason, voided_by=actor.id,
            prior_status=sample.status, prior_issue_reason=sample.issue_reason,
        )
        db.add(void)
        db.flush()

    for sid in sorted(affected):
        item = db.get(FootfallSample, sid)
        if item is not None:
            if item.status != 'excluded':
                item.status = 'excluded'
                item.issue_reason = VOID_ISSUE_REASON
            # A pending correction over contaminated counts must not be approvable.
            for correction in db.scalars(
                select(AttributionCorrection).where(
                    AttributionCorrection.sample_id == sid,
                    AttributionCorrection.status == 'pending',
                ).with_for_update()
            ):
                correction.status = 'rejected'
                correction.reviewed_by = actor.id
                correction.review_note = '样本计数录错已报废，更正单自动终止'
                record(db, actor.email, 'attribution.rejected', {
                    'id': correction.id, 'sample_id': sid, 'decision': 'reject',
                    'reason': 'sample.voided',
                })

    reason_text = f'样本 #{sample.id} 计数录错已报废：{reason}'
    touched, changed_runs = _invalidate_analyses(db, affected, sample.id, reason_text)
    briefs, changed_briefs = _invalidate_briefs(db, touched, reason_text, actor)

    if created:
        record(db, actor.email, 'sample.voided', {
            'sample_id': sample.id, 'affected_sample_ids': sorted(affected),
            'reason': reason,
        })
    if changed_runs:
        record(db, actor.email, 'analysis.invalidated', {
            'analysis_ids': [run.id for run in changed_runs], 'sample_id': sample.id,
        })
    for brief in changed_briefs:
        record(db, actor.email, f'brief.{brief.status}', {
            'id': brief.id, 'analysis_id': brief.analysis_id, 'sample_id': sample.id,
            'reason': reason_text,
        })
    db.flush()
    return {
        'sample_id': sample.id,
        'affected_sample_ids': sorted(affected),
        'analysis_ids': [run.id for run in touched],
        'briefs': [{'id': brief.id, 'analysis_id': brief.analysis_id, 'status': brief.status}
                   for brief in briefs],
        'already_voided': not created,
        'voided_at': void.created_at.isoformat() if void.created_at else None,
        'reason': void.reason,
    }
